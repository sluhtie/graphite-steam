#!/usr/bin/env node
// Graphite build: bundles src/*.css (inlining local @imports) and resolves
// Steam class tokens against the local Steam install.
//
//   $(Key)            class "Key" (must be unique across Steam's CSS modules)
//   $(Key@Anchor)     class "Key" from the module that also defines "Anchor"
//   $(Key@A+B)        ... that defines both "A" and "B"
//
// Usage: node tools/build.mjs [--steam <dir>] [--strict]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findSteamDir, extractModules, makeResolver } from './classmap.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const strict = args.includes('--strict');
const steamArg = args.indexOf('--steam');
const steamDir = steamArg >= 0 ? args[steamArg + 1] : findSteamDir();
if (!steamDir) {
  console.error('Steam installation not found. Pass --steam <dir> or set STEAM_DIR.');
  process.exit(1);
}

const modules = extractModules(steamDir);
const resolve = makeResolver(modules);
console.log(`Steam: ${steamDir}  (${modules.length} class modules)`);

const ENTRY_DIR = path.join(root, 'src');
const OUT_DIR = path.join(root, 'build');
const TOKEN_RE = /\$\(([A-Za-z_][\w-]*(?:@[A-Za-z_][\w-]*(?:\+[A-Za-z_][\w-]*)*)?)\)/g;
const IMPORT_RE = /@import\s+(?:url\()?['"](\.{1,2}\/[^'"]+)['"]\)?\s*;/g;

const problems = new Map();

function bundle(file, stack = []) {
  if (stack.includes(file)) throw new Error('Circular @import: ' + [...stack, file].join(' -> '));
  let css = fs.readFileSync(file, 'utf8');
  css = css.replace(IMPORT_RE, (_, rel) => bundle(path.resolve(path.dirname(file), rel), [...stack, file]));
  return css;
}

function resolveTokens(css, entry) {
  return css.replace(TOKEN_RE, (_, token) => {
    const hits = resolve(token);
    if (hits.length === 1) return hits[0];
    if (hits.length === 0) {
      problems.set(token, `${entry}: "${token}" not found`);
      return `gr-missing-${token.replace(/[@+]/g, '_')}`;
    }
    // With an explicit anchor, several hits are copies of the same module in
    // different bundles (sp.js / library.js) - match all of them silently.
    if (!token.includes('@')) problems.set(token, `${entry}: "${token}" matches ${hits.length} modules - consider an @Anchor`);
    // ambiguous: the token is always used right after a "." so we emit a
    // class list wrapped in :is() by replacing the leading dot below
    return `\u0000${hits.join('\u0001')}\u0000`;
  }).replace(/\.\u0000([^\u0000]+)\u0000/g, (_, list) => `:is(${list.split('\u0001').map(h => '.' + h).join(',')})`);
}

// Entry points: src/*.css and src/options/*.css. Everything in src/partials/
// is only pulled in through @import.
fs.rmSync(OUT_DIR, { recursive: true, force: true });
const entries = [
  ...fs.readdirSync(ENTRY_DIR).filter(f => f.endsWith('.css')),
  ...fs.readdirSync(path.join(ENTRY_DIR, 'options')).filter(f => f.endsWith('.css')).map(f => 'options/' + f),
];
for (const entry of entries) {
  const bundled = bundle(path.join(ENTRY_DIR, entry));
  // keep remote @imports (Google Fonts) at the very top of the sheet
  const remote = [];
  const body = bundled.replace(/@import\s+url\(['"]?https:[^)]+\)\s*;\s*/g, m => { remote.push(m.trim()); return ''; });
  const out = [...remote, `/* Graphite - generated by tools/build.mjs from src/${entry}. Do not edit. */`, resolveTokens(body, entry).trim(), ''].join('\n');
  const dest = path.join(OUT_DIR, entry);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, out);
  console.log(`  build/${entry}  ${(out.length / 1024).toFixed(1)} KB`);
}

if (problems.size) {
  console.warn(`\n${problems.size} token problem(s):`);
  for (const p of problems.values()) console.warn('  - ' + p);
  if (strict) process.exit(1);
} else {
  console.log('All class tokens resolved.');
}
